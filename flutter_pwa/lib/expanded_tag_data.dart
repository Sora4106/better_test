String _expandedTagSlug(String value) => value
    .toLowerCase()
    .replaceAll(RegExp(r'[^a-z0-9]+'), '_')
    .replaceAll(RegExp(r'^_+|_+$'), '');

List<CatalogTagData> _expandedTags({
  required String prefix,
  required String group,
  required int order,
  required bool adult,
  required List<List<String>> rows,
  String? defaultConflictGroup,
}) =>
    rows
        .map((row) => CatalogTagData(
              id: '${prefix}_${_expandedTagSlug(row[1])}',
              group: group,
              zh: row[0],
              en: row[1],
              order: order,
              adult: adult,
              conflictGroup: row.length > 2
                  ? (row[2].isEmpty ? null : row[2])
                  : defaultConflictGroup,
            ))
        .toList();

