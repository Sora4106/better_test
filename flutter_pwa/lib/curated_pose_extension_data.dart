import 'catalog_data.dart';

String _curatedPoseSlug(String value) => value
    .toLowerCase()
    .replaceAll(RegExp(r'[^a-z0-9]+'), '_')
    .replaceAll(RegExp(r'^_+|_+$'), '');

List<CatalogTagData> _curatedPoseGroup(
  String prefix,
  String group,
  List<(String, String)> rows,
) =>
    rows
        .map(
          (row) => CatalogTagData(
            id: 'curated_pose_${prefix}_${_curatedPoseSlug(row.$2)}',
            group: group,
            zh: row.$1,
            en: row.$2,
            order: 4,
            support: 'description',
          ),
        )
        .toList(growable: false);

