/// Converts the supplied pose-kit clauses into readable descriptions. Clauses
/// that are not covered stay in English instead of guessing a different pose.
String describeAttachedPose(String prompt) {
  final translated = <String>[];
  final untranslated = <String>[];
  for (final raw in prompt.split(',')) {
    final part = raw.trim();
    if (part.isEmpty) continue;
    final zh = _translatePoseClause(part.toLowerCase());
    if (zh == null) {
      untranslated.add(part);
    } else if (!translated.contains(zh)) {
      translated.add(zh);
    }
  }
  final result = StringBuffer();
  if (translated.isNotEmpty) result.write('${translated.join('，')}。');
  if (untranslated.isNotEmpty) {
    result.write('其他細節（英文原文）：${untranslated.join('，')}。');
  }
  return result.toString();
}

String? _translatePoseClause(String value) {
  final exact = _poseClauses[value];
  if (exact != null) return exact;

  final hands =
      RegExp(r'^(one hand|other hand|both hands|hands) (?:is |are )?(.*)$')
          .firstMatch(value);
  if (hands != null) {
    final subject = const {
      'one hand': '一隻手',
      'other hand': '另一隻手',
      'both hands': '雙手',
      'hands': '雙手'
    }[hands.group(1)]!;
    final action = _handActions[hands.group(2)];
    if (action != null) return '$subject$action';
  }

  final matching = RegExp(
          r'^(one knee|other knee|knees|one leg|other leg|legs|one foot|other foot|feet) (.*)$')
      .firstMatch(value);
  if (matching != null) {
    final subject = const {
      'one knee': '一邊膝蓋',
      'other knee': '另一邊膝蓋',
      'knees': '雙膝',
      'one leg': '一條腿',
      'other leg': '另一條腿',
      'legs': '雙腿',
      'one foot': '一隻腳',
      'other foot': '另一隻腳',
      'feet': '雙腳',
    }[matching.group(1)]!;
    final action = _limbActions[matching.group(2)];
    if (action != null) return '$subject$action';
  }
  return null;
}

